"""
Topic: Dynamic Typing

Concept:
Check the type of an object using type().

Real-World Example:
Validating data before processing.
"""

student_name = "Kalid"
student_age = 28
student_marks = 95.5
student_passed = True

print("Data Types")
print("----------")

print(student_name, ":", type(student_name))
print(student_age, ":", type(student_age))
print(student_marks, ":", type(student_marks))
print(student_passed, ":", type(student_passed))