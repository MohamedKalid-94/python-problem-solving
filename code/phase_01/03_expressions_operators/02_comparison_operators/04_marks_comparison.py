"""
Topic: Comparison Operators

Concept:
Compare student marks.
"""


student_1_marks = 85

student_2_marks = 92


print("Student Marks Comparison")
print("------------------------")


print(
    "Student 1 scored higher:",
    student_1_marks > student_2_marks
)


print(
    "Student 2 scored higher:",
    student_2_marks > student_1_marks
)


print(
    "Both have same marks:",
    student_1_marks == student_2_marks
)