number_1 = 20
number_2 = 5

addition = number_1 + number_2
subtraction = number_1 - number_2
multiplication = number_1 * number_2
division = number_1 / number_2
modulus = number_1 % number_2
floor_division = number_1 // number_2
power = number_1 ** 2


print("Basic Calculations")
