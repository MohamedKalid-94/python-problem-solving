"""
Topic: Dynamic Typing

Concept:
Python variables can point to different data types during runtime.

Real-World Example:
A variable storing different types of information.
"""

data = 100

print("Initial Value")
print("-------------")
print(data)
print(type(data))

data = "Python"

print()

print("After Changing Value")
print("--------------------")
print(data)
print(type(data))

data = 10.5

print()

print("After Changing Again")
print("--------------------")
print(data)
print(type(data))