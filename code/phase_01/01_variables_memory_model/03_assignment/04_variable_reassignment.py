"""
Topic: Assignment

Concept:
Variables can be reassigned with new values.

Real-World Example:
Updating an employee's salary.
"""

salary = 50000

print("Initial Salary")
print("--------------")
print(salary)

salary = 55000

print()

print("Updated Salary")
print("--------------")
print(salary)

salary = 60000

print()

print("Final Salary")
print("------------")
print(salary)