"""
Topic: Comparison Operators

Concept:
Compare two numbers.

Operators:
==
!=
>
<
>=
<=
"""


number_1 = 50

number_2 = 30


print("Number Comparison")
print("-----------------")


print("Equal :", number_1 == number_2)

print("Not Equal :", number_1 != number_2)

print("Greater :", number_1 > number_2)

print("Smaller :", number_1 < number_2)

print("Greater or Equal :", number_1 >= number_2)

print("Smaller or Equal :", number_1 <= number_2)